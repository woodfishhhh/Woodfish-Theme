// docs/hosts/jetbrains-keys.md: where every mapped attribute name was found, and which VS Code scope it follows.
const scopeMap = require('./scopeMap');
const verified = require('./verified-keys.json');

const GROUPS = [
  ['Java', (key) => /^(JAVA_|[A-Z_]+_ATTRIBUTES$)/.test(key) && !key.startsWith('KOTLIN_')],
  ['Kotlin', (key) => key.startsWith('KOTLIN_')],
  ['Python', (key) => key.startsWith('PY.')],
  ['JSON', (key) => key.startsWith('JSON.')],
  ['Markdown', (key) => key.startsWith('MARKDOWN_')],
  ['TypeScript', (key) => key.startsWith('TS.')],
  ['Go', (key) => key.startsWith('GO_')],
  ['Rust', (key) => key.startsWith('org.rust.')],
  ['Shared (DEFAULT_*)', () => true],
];

/** Parent-scheme attributes are listed with the platform ones even though their names end in _ATTRIBUTES. */
const PLATFORM = new Set([
  'ANNOTATION_NAME_ATTRIBUTES',
  'ANNOTATION_ATTRIBUTE_NAME_ATTRIBUTES',
  'STATIC_METHOD_ATTRIBUTES',
  'TYPE_PARAMETER_NAME_ATTRIBUTES',
  'IMPLICIT_ANONYMOUS_CLASS_PARAMETER_ATTRIBUTES',
  'INSTANCE_FIELD_ATTRIBUTES',
  'STATIC_FIELD_ATTRIBUTES',
  'STATIC_FINAL_FIELD_ATTRIBUTES',
]);

function groupOf(key) {
  if (key.startsWith('DEFAULT_') || PLATFORM.has(key)) return 'Shared (DEFAULT_*)';
  return GROUPS.find(([, test]) => test(key))[0];
}

function products(key) {
  return Object.keys(verified[key] ?? {})
    .map((label) => label.replace(/ \(.*\)$/, '') + ' ' + (label.match(/\((.*)\)/)?.[1] ?? ''))
    .map((text) => text.trim())
    .join(', ');
}

function keyTable() {
  const lines = [
    '# JetBrains attribute names',
    '',
    '<!-- generated by `pnpm jetbrains:generate` from scripts/scopeMap.js and scripts/verified-keys.json -->',
    '',
    'Every token attribute the generated editor schemes set. “Found in” lists the IDE distributions or plugins whose',
    'classes or scheme files contain the name (`scripts/audit-keys.py`); “VS Code scope” is the TextMate scope',
    'stack whose color the attribute gets. The editor colors (background, caret, selection, search, errors) come',
    'from the theme’s own `editor.*` colors, see [jetbrains.md](./jetbrains.md).',
    '',
  ];
  for (const [group] of GROUPS) {
    const rows = scopeMap.filter(({ key }) => groupOf(key) === group);
    if (!rows.length) continue;
    lines.push(
      `## ${group}`,
      '',
      '| Attribute | Found in | VS Code scope |',
      '| --- | --- | --- |'
    );
    for (const { key, scopes } of rows)
      lines.push(`| \`${key}\` | ${products(key)} | \`${scopes}\` |`);
    lines.push('');
  }
  return lines.join('\n');
}

module.exports = { keyTable, groupOf };
